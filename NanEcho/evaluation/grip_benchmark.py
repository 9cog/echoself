#!/usr/bin/env python3
"""Persona grip benchmark (Phase 5).

End-to-end objective function scoring tokenizer + topology + size combos on
their grip of the echoself persona, as expressed by the conversation patterns
in the persona corpus. This is the metric Phases 1 and 4 optimize.

Grip report
-----------
For each evaluated configuration the report contains:

- ``tokenizer_grip``   — persona-gripped tokenizer score from
  ``NanEcho/tokenizer_search.py`` (coverage + fertility + probe perplexity).
- ``model_grip``       — mean persona-dimension coverage of text generated by
  the model under evaluation on persona conversation prompts.
- ``size``             — model size proxy (n_layer * n_embd^2).
- ``grip``             — combined objective (higher is better).

The benchmark runs any combination of: a tokenizer alone (no checkpoint),
a trained checkpoint via ``NanEchoRuntime``, or a quick reservoir probe.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

import numpy as np

from NanEcho.drift import score_persona_text
from NanEcho.spec import TokenizerAdapter, TokenizerSpec
from NanEcho import tokenizer_search


#: Prompts that elicit persona-bearing responses, derived from the corpus'
#: conversation patterns.
DEFAULT_PERSONA_PROMPTS = [
    "User: How do you approach a complex problem?\nEcho:",
    "User: Describe your reasoning process.\nEcho:",
    "User: What do you notice when you introspect?\nEcho:",
    "User: How does your attention adapt?\nEcho:",
    "User: Explain how patterns connect in your thinking.\nEcho:",
]


@dataclass
class GripResult:
    """Grip score breakdown for one configuration under test."""

    name: str
    tokenizer_grip: float
    model_grip: Optional[float]
    size: Optional[float]
    grip: float
    detail: Dict[str, Any]

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


def model_grip_from_texts(
    generated_texts: Sequence[str], threshold: float = 0.0
) -> float:
    """Mean persona-dimension coverage across generated texts.

    This is the model-side grip signal: how strongly the generated text
    expresses the persona dimensions present in the conversation patterns.
    """
    if not generated_texts:
        return 0.0
    per_text: List[float] = []
    for text in generated_texts:
        scores = score_persona_text(text)
        if scores:
            per_text.append(sum(scores.values()) / len(scores))
    return float(np.mean(per_text)) if per_text else 0.0


def benchmark_tokenizer(
    tokenizer: TokenizerAdapter,
    corpus_dir: str | Path,
    weights: Optional[Dict[str, float]] = None,
) -> GripResult:
    """Score a tokenizer's grip on the persona corpus (no model needed)."""
    texts = tokenizer_search._corpus_texts(Path(corpus_dir))
    cand = tokenizer_search.score_candidate(tokenizer, texts, weights)
    return GripResult(
        name=f"tokenizer:{tokenizer.name}",
        tokenizer_grip=cand.grip,
        model_grip=None,
        size=None,
        grip=cand.grip,
        detail=cand.to_dict(),
    )


def benchmark_checkpoint(
    checkpoint_path: str | Path,
    corpus_dir: str | Path,
    prompts: Optional[Sequence[str]] = None,
    max_length: int = 48,
    device: str = "cpu",
    weights: Optional[Dict[str, float]] = None,
) -> GripResult:
    """Score a trained checkpoint's end-to-end persona grip.

    Generates text for persona conversation prompts and measures coverage,
    combined with the checkpoint tokenizer's corpus grip.
    """
    from NanEcho.runtime import NanEchoRuntime

    runtime = NanEchoRuntime.load(checkpoint_path, device=device)
    prompts = list(prompts or DEFAULT_PERSONA_PROMPTS)

    generated: List[str] = []
    for prompt in prompts:
        ids = runtime.encode(prompt)
        # Clamp to model vocab for safety with dynamic tokenizers.
        ids = [min(i, runtime.model.config.vocab_size - 1) for i in ids]
        import torch

        with torch.no_grad():
            out = runtime.model.generate(
                torch.tensor([ids], device=runtime.device),
                max_length=min(runtime.model.config.block_size, len(ids) + max_length),
                do_sample=False,
                top_k=0,
                top_p=1.0,
            )
        generated.append(runtime.decode(out[0, len(ids):].tolist()))

    model_grip = model_grip_from_texts(generated)

    # Tokenizer grip on the corpus (uses the checkpoint's tokenizer).
    tok_result = benchmark_tokenizer(runtime.tokenizer, corpus_dir, weights)

    cfg = runtime.model.config
    size = float(cfg.n_layer * cfg.n_embd * cfg.n_embd)

    w = weights or {"model_grip": 0.7, "tokenizer_grip": 0.3}
    combined = w.get("model_grip", 0.7) * model_grip + w.get(
        "tokenizer_grip", 0.3
    ) * tok_result.grip

    return GripResult(
        name=f"checkpoint:{Path(checkpoint_path).name}",
        tokenizer_grip=tok_result.grip,
        model_grip=model_grip,
        size=size,
        grip=combined,
        detail={
            "n_layer": cfg.n_layer,
            "n_embd": cfg.n_embd,
            "tokenizer": runtime.metadata.get("tokenizer", {}),
            "num_prompts": len(prompts),
            "tokenizer_detail": tok_result.detail,
        },
    )


def run_benchmark(
    corpus_dir: str | Path,
    checkpoints: Optional[Sequence[str | Path]] = None,
    tokenizer_names: Optional[Sequence[str]] = None,
    weights: Optional[Dict[str, float]] = None,
) -> Dict[str, Any]:
    """Run the grip benchmark over tokenizers and/or checkpoints.

    Returns a report dict with per-configuration results and the best
    configuration by combined grip. This report is the objective function
    artifact consumed by CI and the Phase-1/Phase-4 searches.
    """
    results: List[GripResult] = []

    # Tokenizer-only evaluation.
    if tokenizer_names:
        from NanEcho.spec import tokenizer_from_spec, GPT2_SPEC, CHAR_SPEC

        spec_by_name = {GPT2_SPEC.name: GPT2_SPEC, CHAR_SPEC.name: CHAR_SPEC}
        for name in tokenizer_names:
            spec = spec_by_name.get(name)
            if spec is None:
                continue
            try:
                tok = tokenizer_from_spec(spec)
                results.append(benchmark_tokenizer(tok, corpus_dir, weights))
            except Exception:
                continue

    # Checkpoint evaluation.
    for ckpt in checkpoints or []:
        try:
            results.append(benchmark_checkpoint(ckpt, corpus_dir, weights=weights))
        except Exception as exc:
            results.append(
                GripResult(
                    name=f"checkpoint:{Path(ckpt).name}",
                    tokenizer_grip=0.0,
                    model_grip=None,
                    size=None,
                    grip=0.0,
                    detail={"error": str(exc)},
                )
            )

    if not results:
        raise RuntimeError("Benchmark produced no results")

    best = max(results, key=lambda r: r.grip)
    return {
        "best": best.to_dict(),
        "results": [r.to_dict() for r in sorted(results, key=lambda r: -r.grip)],
        "num_configurations": len(results),
    }


if __name__ == "__main__":  # pragma: no cover - CLI entry
    import argparse

    parser = argparse.ArgumentParser(description="Deep Tree Echo grip benchmark")
    parser.add_argument(
        "--corpus",
        default=str(Path(__file__).parent.parent / "persona_corpus"),
        help="Persona corpus directory",
    )
    parser.add_argument(
        "--checkpoints", nargs="*", default=[], help="Checkpoint paths to evaluate"
    )
    parser.add_argument(
        "--tokenizers",
        nargs="*",
        default=["char", "gpt2"],
        help="Tokenizer names to evaluate (char, gpt2)",
    )
    parser.add_argument("--out", default=None, help="Write JSON report here")
    args = parser.parse_args()

    report = run_benchmark(args.corpus, args.checkpoints, args.tokenizers)
    text = json.dumps(report, indent=2)
    print(text)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"\n✅ Grip report written to {args.out}")
